export function ItemTypeIcon({ type, className = '', size = 16 }: { type: 'text' | 'url' | 'file'; className?: string; size?: number }) {
  if (type === 'url') return <LinkIcon className={className} size={size} />;
  if (type === 'file') return <FileIcon className={className} size={size} />;
  return <TextIcon className={className} size={size} />;
}
